// 会话技术主键（#116）：进程内单调 ULID。
//
// 本人超过 3 段会话时，结束最旧的一段。取哪一段靠 (认证时间, 会话 id) 排序的第一段。
// 认证时间只到毫秒，同一毫秒内建立的两段会话认证时间相同，排序只能靠会话 id。无状态
// 生成器给出的 id 同毫秒内大小随机，于是同一毫秒内建立两段时，被结束的那段不确定。
//
// 本模块的生成器在进程内单调：同一进程内后建立的会话 id 严格大于先建立的。认证时间相同时
// 按 id 升序，取到的第一段就是先建立的那段。
//
// 时间源：id 的时间部取写入认证时间的那一次时钟读数——同一次读数，两者不打架。
//
// 边界（与 #114 留痕编号同）：单调只在同一进程内成立。多实例部署时同一毫秒内的先后仍然
// 随机。时钟回拨期间 id 的时间部会领先墙钟，直到墙钟追上。

import { createMonotonicUlidGenerator } from '@natural-enforcement/identity';

/** 本进程的会话 id 生成器。同一进程内单调。参数是写入认证时间的那一次时钟读数（毫秒）。 */
export const newSessionId = createMonotonicUlidGenerator();
